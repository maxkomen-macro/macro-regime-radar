/**
 * web/scripts/gen-ddl-fixture.mjs — generate the DDL fixture from the one copy
 * of the proposed Snowflake export schema (DESK_FRAME3_SPEC §12.9, S-04;
 * docs/desk/FRAME3_API_PLAN.md §1.9, R-02).
 *
 * `api/static/snowflake_proposed.sql` is what GET /api/desk/pipeline/ddl serves
 * verbatim. The web fixture must say the same, but nothing under web/ imports a
 * .sql file: this script reads it and writes `src/fixtures/desk/pipeline-ddl.ts`,
 * a TypeScript module exporting the text as `PIPELINE_DDL`, escaping backslashes,
 * backticks and `${` for the template literal. `src/fixtures/desk/pipeline-ddl.test.ts`
 * holds the export equal to the file byte for byte, and the module equal to what
 * this script writes, so an edit to either side alone fails.
 *
 * Every change to the DDL is an edit to the .sql file, then (from web/):
 *     node scripts/gen-ddl-fixture.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

// Resolved from this file when node runs it (a test imports only the pure functions below).
const SQL = "../../api/static/snowflake_proposed.sql";
const OUT = "../src/fixtures/desk/pipeline-ddl.ts";

const HEADER = `/**
 * GENERATED by web/scripts/gen-ddl-fixture.mjs from api/static/snowflake_proposed.sql;
 * do not edit by hand: edit the .sql file and run \`node scripts/gen-ddl-fixture.mjs\`
 * from web/.
 *
 * The fixture for GET /api/desk/pipeline/ddl (DESK_FRAME3_SPEC §12.9): the
 * proposed Snowflake export schema, the three layers the bridge card shows (RAW,
 * CUR, MART), as the route serves it (S-04). A .ts module, never a .sql import
 * (R-02): the browser tests (Node) and the dev server read it the way the JSON
 * fixtures are read. pipeline-ddl.test.ts holds it equal to the file byte for
 * byte. The text starts with the file's first line, which says the schema is
 * proposed.
 */
`;

/** The template literal's body for `sql`: backslashes, backticks and `${` escaped. */
export function escapeTemplate(sql) {
  return sql.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

/** The module this script writes for `sql`. */
export function render(sql) {
  return `${HEADER}export const PIPELINE_DDL = \`${escapeTemplate(sql)}\`;\n`;
}

function main() {
  const sqlPath = fileURLToPath(new URL(SQL, import.meta.url));
  const outPath = fileURLToPath(new URL(OUT, import.meta.url));
  const sql = readFileSync(sqlPath, "utf8");
  writeFileSync(outPath, render(sql));
  console.log(`wrote ${outPath} (${Buffer.byteLength(sql, "utf8")} bytes of DDL)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
